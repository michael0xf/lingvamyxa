function Write-InboxNudge {
    $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
    $name = "$stamp.txt"
    $body = Get-MikhailLetter
    foreach ($inbox in @($fableInbox, $claudeInbox)) {
        $path = Join-Path $inbox $name
        # Tiny stagger if same second collision (unlikely across dirs with same name is fine / desired)
        [System.IO.File]::WriteAllText($path, $body, [System.Text.UTF8Encoding]::new($false))
        Write-Output "WROTE $path"
    }
}

Write-Output "MIKHAIL_30M_WATCHER_START pid=$PID interval=${intervalSec}s targets=fable,claude"
if ($env:MIKHAIL_SKIP_FIRST -ne '1') {
    Write-InboxNudge
}
while ($true) {
    Start-Sleep -Seconds $intervalSec
    Write-InboxNudge
}
